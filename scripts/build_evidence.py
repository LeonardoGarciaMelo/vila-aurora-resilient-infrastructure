#!/usr/bin/env python3
"""Curates raw lab output into the versioned evidence/ tree, indexed by requirement.

Removes local paths, then refuses to finish if a value from .env or a private key appears in any file.
Large images (EV-01, EV-02) stay in the ignored evidence/forensics/images; their hashes are versioned.
"""
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "evidence/raw"
FORENSICS = ROOT / "evidence/forensics"
RESULTS = ROOT / "docs/results"
EVIDENCE = ROOT / "evidence"
MAX_COPY_BYTES = 2_000_000
LAYOUT = {
    "01_sql_injection": [("security", ["SQLI_*", "APP_*", "waf_rule*"]), ("attacker", ["sqlmap_*", "stacked_response.html", "v1_manual_or*"])],
    "02_device_identity": [("security", ["T1*", "T2*", "T3*", "T4*"])],
    "03_vpn_segmentation": [("security", ["T5*", "T6*", "T7*", "T8*"])],
    "04_detection_response": [("security", ["DET_*"])],
}
RESULT_COPIES = {
    "01_sql_injection": [], "04_detection_response": ["security_results.json"],
    "05_mail_authentication": ["mail_auth_results.txt"], "06_phishing_simulation": ["phishing_results.json"],
    "07_ai": ["ai_anomaly_metrics.json", "llm_triage_metrics.json"],
    "08_resilience": ["chaos_results.json", "chaos_timeseries.csv", "edge_resources.json"],
    "10_accessibility": ["accessibility_results.json"],
}
INDEX = """# Evidence Index

Generated by `scripts/build_evidence.py` from real runs of this lab. All data is synthetic.

| Folder | Requirements | Contents |
| --- | --- | --- |
| `01_sql_injection` | RT-08 | sqlmap against v1 and v2, manual payloads, panel checks |
| `02_device_identity` | RT-04, RT-05 | Tests T1 to T4: no certificate, foreign CA, foreign topic, revocation, serials |
| `03_vpn_segmentation` | RT-06, RT-07 | Tests T5 to T8: port scans, tunnels, MFA gate, blocked segments |
| `04_detection_response` | RT-12, RT-13, RT-15 | Detection scenarios, SOAR actions, all SIEM alerts, full suite results |
| `05_mail_authentication` | RT-10 | DNS records, verdicts, legitimate and forged messages |
| `06_phishing_simulation` | RT-11 | Gophish metrics. Scripted personas: pipeline validation, not human results |
| `07_ai` | RT-16, RT-17 | Anomaly and LLM metrics, prompt injection results |
| `08_resilience` | RT-02, RT-22, RT-23 | Chaos test results and time series, edge resources, availability |
| `09_forensics` | RT-14 | Hashes, chain of custody, timeline, verification, attack ground truth, log bundles |
| `10_accessibility` | RT-21 | axe-core results and panel screenshots |

`EV-01` and `EV-02` are too large to version. Run `make incident` to regenerate them; `09_forensics/hashes.json`
records the hashes of the images from the reported run. Regenerated images will have different hashes.
"""


def copy(source: Path, target_dir: Path) -> None:
    target_dir.mkdir(parents=True, exist_ok=True)
    target = target_dir / (source.name.removesuffix(".log") + ".txt" if source.suffix == ".log" else source.name)
    shutil.copyfile(source, target)


def secret_values() -> list[str]:
    values = []
    for line in (ROOT / ".env").read_text().splitlines():
        if "=" in line and not line.startswith("#"):
            name, value = line.split("=", 1)
            if any(word in name for word in ("PASSWORD", "SECRET", "TOKEN", "KEY", "TOTP")) and len(value) >= 8:
                values.append(value)
    demo = ROOT / "secrets/lab/demo_users.json"
    if demo.exists():
        for user in json.loads(demo.read_text()).values():
            values += [user["password"], user["totp_secret"]]
    return values


def scrub_and_check() -> list[str]:
    secrets, problems = secret_values(), []
    for path in EVIDENCE.rglob("*"):
        if not path.is_file() or path.is_relative_to(RAW) or path.is_relative_to(FORENSICS) or path.suffix in (".png", ".tar"):
            continue
        text = path.read_text(errors="replace")
        cleaned = text.replace(str(ROOT), "<repo>").replace(str(Path.home()), "<home>")
        if cleaned != text:
            path.write_text(cleaned)
        if "PRIVATE KEY-----" in cleaned or any(value in cleaned for value in secrets):
            problems.append(str(path.relative_to(ROOT)))
    # Tar bundles are checked through their text content too.
    for path in EVIDENCE.rglob("*.tar"):
        if path.is_relative_to(FORENSICS):
            continue
        listing = subprocess.run(["tar", "-xOf", str(path)], capture_output=True).stdout.decode(errors="replace")
        if "PRIVATE KEY-----" in listing or any(value in listing for value in secrets):
            problems.append(str(path.relative_to(ROOT)))
    return problems


def main() -> None:
    for folder, groups in LAYOUT.items():
        for source, patterns in groups:
            for pattern in patterns:
                for path in sorted((RAW / source).glob(pattern)):
                    copy(path, EVIDENCE / folder)
    for folder, names in RESULT_COPIES.items():
        for name in names:
            if (RESULTS / name).exists():
                copy(RESULTS / name, EVIDENCE / folder)
    for path in sorted((RAW / "mail").rglob("*.eml")):
        copy(path, EVIDENCE / "05_mail_authentication" / path.parent.name)
    for path in sorted((RESULTS / "screenshots").glob("*.png")):
        copy(path, EVIDENCE / "10_accessibility/screenshots")

    target = EVIDENCE / "09_forensics"
    for name in ("hashes.json", "hashes_at_collection.txt", "chain_of_custody.csv", "timeline.csv", "verification_at_collection.txt"):
        if (FORENSICS / name).exists():
            copy(FORENSICS / name, target)
    if (RAW / "attacker/incident_steps.log").exists():
        copy(RAW / "attacker/incident_steps.log", target)
    for name in ("forensics_summary.json", "memory_analysis.json"):
        if (RESULTS / name).exists():
            copy(RESULTS / name, target)
    for path in sorted((FORENSICS / "images").glob("*")):
        if path.stat().st_size <= MAX_COPY_BYTES:
            copy(path, target / "bundles")

    alerts = FORENSICS / "images/EV-07_wazuh_alerts.json"
    if alerts.exists():
        keep = [line for line in alerts.read_text(errors="replace").splitlines() if '"id":"100' in line]
        (EVIDENCE / "04_detection_response/siem_alerts_custom_rules.jsonl").write_text("\n".join(keep) + "\n")

    (EVIDENCE / "README.md").write_text(INDEX)
    problems = scrub_and_check()
    if problems:
        sys.exit("SECRET FOUND, do not version these files:\n" + "\n".join(problems))
    files = [p for p in EVIDENCE.rglob("*") if p.is_file() and not p.is_relative_to(RAW) and not p.is_relative_to(FORENSICS)]
    print(f"evidence ready: {len(files)} files, {sum(p.stat().st_size for p in files) / 1e6:.1f} MB, secret scan clean")


if __name__ == "__main__":
    main()
